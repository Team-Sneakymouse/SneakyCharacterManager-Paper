-- SCM schema contract v1. Operator-applied to the database configured in SneakyDB.
-- The plugin NEVER runs this file or imports YAML. Apply/import offline before opting in.
-- owner_id and character_id are TEXT, including literal owner 'template' and legacy ids.
-- Empty strings are preserved. Reference-like fields intentionally have NO foreign keys:
-- legacy last-played, skin and title references may be unresolved; do not repair on import.
-- Import character ordinal in original YAML insertion order (including disabled entries).
-- ordinal is global identity by default; explicit importer ordinals are accepted. After
-- explicit inserts reset its sequence above MAX(ordinal). owner revision starts at zero.
BEGIN;
CREATE SCHEMA scm;
CREATE TABLE scm.schema_version (singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton), version integer NOT NULL);
INSERT INTO scm.schema_version VALUES (true, 1);
CREATE TABLE scm.owners (
    owner_id text PRIMARY KEY,
    last_played_character text NOT NULL DEFAULT '',
    revision bigint NOT NULL DEFAULT 0
);
CREATE TABLE scm.characters (
    owner_id text NOT NULL REFERENCES scm.owners(owner_id),
    character_id text NOT NULL,
    ordinal bigint GENERATED BY DEFAULT AS IDENTITY,
    enabled boolean NOT NULL DEFAULT true,
    name text NOT NULL DEFAULT '',
    skin_id text NOT NULL DEFAULT '',
    skin text NOT NULL DEFAULT '',
    skin_uuid text NOT NULL DEFAULT '',
    texture text NOT NULL DEFAULT '',
    signature text NOT NULL DEFAULT '',
    slim boolean NOT NULL DEFAULT false,
    tags text NOT NULL DEFAULT '',
    gender text NOT NULL DEFAULT '',
    title text NOT NULL DEFAULT '',
    PRIMARY KEY (owner_id, character_id),
    UNIQUE (owner_id, ordinal)
);
CREATE TABLE scm.skins (
    skin_id text PRIMARY KEY,
    mojang_url text NOT NULL DEFAULT '',
    texture text NOT NULL DEFAULT '',
    signature text NOT NULL DEFAULT ''
);
-- Index aliases exactly as stored by GlobalSkinCache; multiple URLs may share content.
CREATE TABLE scm.skin_sources (
    source_url text PRIMARY KEY,
    skin_id text NOT NULL
);
CREATE INDEX skins_mojang_url ON scm.skins(mojang_url);
CREATE TABLE scm.uniform_variants (
    base_url text NOT NULL,
    uniform_hash text NOT NULL,
    skin_uuid text NOT NULL DEFAULT '',
    texture_url text NOT NULL DEFAULT '',
    texture text NOT NULL DEFAULT '',
    signature text NOT NULL DEFAULT '',
    PRIMARY KEY (base_url, uniform_hash)
);
CREATE TABLE scm.titles (
    code text PRIMARY KEY,
    display text NOT NULL
);
COMMIT;
